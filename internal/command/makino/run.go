// Package makino implements the server administrator command-line tool.
package makino

import (
	"context"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"time"
)

// Run executes one management command. User commands use the HTTP admin API;
// server catalog commands connect to MongoDB without starting the game server.
func Run(ctx context.Context, args []string, stdout, stderr io.Writer) error {
	flags := flag.NewFlagSet("makino", flag.ContinueOnError)
	flags.SetOutput(stderr)
	serverDefault := os.Getenv("MAKINO_SERVER_URL")
	if serverDefault == "" {
		serverDefault = "http://localhost:50052"
	}
	serverURL := flags.String("server", serverDefault, "HTTP admin server URL (or MAKINO_SERVER_URL)")
	timeout := flags.Duration("timeout", 30*time.Second, "command timeout")
	flags.Usage = func() { printUsage(stderr) }
	if err := flags.Parse(args); err != nil {
		if errors.Is(err, flag.ErrHelp) {
			return nil
		}
		return err
	}
	args = flags.Args()
	if len(args) == 0 || args[0] == "help" {
		printUsage(stdout)
		return nil
	}
	if *timeout <= 0 {
		return errors.New("--timeout must be positive")
	}
	ctx, cancel := context.WithTimeout(ctx, *timeout)
	defer cancel()
	switch args[0] {
	case "user":
		return runUser(ctx, *serverURL, args[1:], stdout, stderr)
	case "server":
		return runServer(ctx, args[1:], stdout, stderr)
	default:
		return errors.New("unknown command; use makino --help")
	}
}

func printUsage(out io.Writer) {
	fmt.Fprintln(out, `Usage: makino [--server URL] [--timeout 30s] <user|server> <command> [flags]

Global flags must precede user/server. The .env file in the working directory
is loaded by the binary. User commands require SOLIS_ADMIN_AUTH and use
MAKINO_SERVER_URL (default http://localhost:50052) unless --server is supplied.
Use HTTPS when connecting to a remote admin server.

User commands:
  user create [--id PUBLIC_ID] [--suid UUID] [--password PASSWORD]
    Omitted values are generated by the server. The response includes credentials.
  user god <--id PUBLIC_ID|--suid UUID> [--message all|enjoy|none]
    [--fan all|enjoy|none] [--bond all|enjoy|none]; omitted features default to all.
  user delete <--id PUBLIC_ID|--suid UUID>

Server catalogs:
  server <catalog> --help
    Manage database-backed catalogs; requires SOLIS_DB_URI.
    Use makino server --help for the supported catalog names and operations.`)
}
